#ifndef PSRAM_BASE
#define PSRAM_BASE  0x60000000
#endif
#define EPD_U8G2_W  528
#define EPD_U8G2_H  792
#define EPD_U8G2_TW (EPD_U8G2_W / 8)
#define EPD_U8G2_TH (EPD_U8G2_H / 8)
#define EPD_U8G2_BUF_SIZE (EPD_U8G2_TW * EPD_U8G2_TH * 8)

static uint8_t *g_u8g2_buf = (uint8_t *)PSRAM_BASE;

static const u8x8_display_info_t u8x8_epd_528x792_display_info =
{
    .chip_enable_level = 0,
    .chip_disable_level = 1,
    .post_chip_enable_wait_ns = 0,
    .pre_chip_disable_wait_ns = 0,
    .reset_pulse_width_ms = 0,
    .post_reset_wait_ms = 0,
    .sda_setup_time_ns = 0,
    .sck_pulse_width_ns = 0,
    .sck_clock_hz = 0,
    .spi_mode = 0,
    .i2c_bus_clock_100kHz = 0,
    .data_setup_time_ns = 0,
    .write_pulse_width_ns = 0,
    .tile_width = EPD_U8G2_TW,
    .tile_height = EPD_U8G2_TH,
    .default_x_offset = 0,
    .flipmode_x_offset = 0,
    .pixel_width = EPD_U8G2_W,
    .pixel_height = EPD_U8G2_H,
};

static uint8_t u8x8_d_epd_528x792_cb(u8x8_t *u8x8, uint8_t msg, uint8_t arg_int, void *arg_ptr)
{
    (void)arg_int;
    (void)arg_ptr;
    switch (msg)
    {
    case U8X8_MSG_DISPLAY_SETUP_MEMORY:
        u8x8_d_helper_display_setup_memory(u8x8, &u8x8_epd_528x792_display_info);
        break;
    case U8X8_MSG_DISPLAY_INIT:
        u8x8_d_helper_display_init(u8x8);
        break;
    default:
        break;
    }
    return 1;
}

static uint8_t u8x8_gpio_and_delay_cb(u8x8_t *u8x8, uint8_t msg, uint8_t arg_int, void *arg_ptr)
{
    (void)u8x8;
    (void)arg_int;
    (void)arg_ptr;
    switch (msg)
    {
    case U8X8_MSG_DELAY_MILLI:
        rt_thread_mdelay(arg_int);
        break;
    case U8X8_MSG_DELAY_10MICRO:
        HAL_Delay_us(10);
        break;
    case U8X8_MSG_DELAY_100NANO:
        HAL_Delay_us(1);
        break;
    default:
        break;
    }
    return 1;
}

static uint8_t u8x8_byte_cb(u8x8_t *u8x8, uint8_t msg, uint8_t arg_int, void *arg_ptr)
{
    (void)u8x8;
    (void)arg_int;
    (void)arg_ptr;
    return 1;
}

void u8g2_port_init(u8g2_t *u8g2)
{
    memset(g_u8g2_buf, 0, EPD_U8G2_BUF_SIZE);

    u8x8_Setup(u8g2_GetU8x8(u8g2),
               u8x8_d_epd_528x792_cb,
               u8x8_cad_empty,
               u8x8_byte_cb,
               u8x8_gpio_and_delay_cb);

    u8g2_SetupBuffer(u8g2, g_u8g2_buf, EPD_U8G2_TH,
                      u8g2_ll_hvline_vertical_top_lsb, U8G2_R0);

    u8g2_SetFont(u8g2, u8g2_font_6x10_tf);
}

